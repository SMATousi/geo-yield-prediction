def group_header(width: int, first_col: int = 2) -> str:
    """A header row naming the three model groups, `width` columns per model, plus its cmidrules."""
    cells, rules, c = [], [], first_col
    for name, n in GROUPS:
        cells.append(r'\multicolumn{%d}{c}{%s}' % (n * width, name))
        rules.append(r'\cmidrule(lr){%d-%d}' % (c, c + n * width - 1))
        c += n * width
    return ' & ' + ' & '.join(cells) + r' \\' + '\n' + ''.join(rules) + '\n'


def f2(x, signed=False):
    s = ('%+.3f' if signed else '%.3f') % x
    return s.replace('-', '$-$') if not signed else s.replace('-', '$-$').replace('+', '$+$')


def ci(v):
    """[point, lo, hi] -> '+0.016 [+0.010, +0.022]' with bold when the CI excludes 0."""
    pt, lo, hi = v
    s = r'%s {\scriptsize[%s, %s]}' % (f2(pt, True), f2(lo, True), f2(hi, True))
    return r'\textbf{%s}' % s if lo > 0 or hi < 0 else s


def bold_best(v, t, key, fmt, best):
    """v[t][key] formatted as in f2, bold when it is the best of the row's models at the printed precision (ties all bold)."""
    shown = lambda x: float(fmt % x)
    s = fmt % v[t][key]
    s = s.replace('-', '$-$')
    return r'\textbf{%s}' % s if shown(v[t][key]) == best(shown(v[m][key]) for m, _ in MODELS) else s


def write(name, body):
    (OUT / name).write_text('%% generated by geo-yield-prediction/results/paper_tables.py -- do not edit\n' + body)


